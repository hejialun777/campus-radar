/* ---------------------------------------------------------------------------
 * 检查一段文本
 * 返回 { ok, hits: [{ cat, catName, icon, label, word, level }] }
 * ------------------------------------------------------------------------- */
window.checkContent = function (text) {
  var src = String(text || '');
  if (!src.trim()) return { ok: true, hits: [] };

  var hits = [];
  var seen = {};

  window.MODERATION_RULES.forEach(function (cat) {
    cat.items.forEach(function (rule) {
      var m = src.match(rule.re);
      if (!m) return;
      var key = cat.key + '|' + m[0];
      if (seen[key]) return;
      seen[key] = true;
      hits.push({
        cat: cat.key,
        catName: cat.name,
        icon: cat.icon,
        desc: cat.desc,
        label: rule.label,
        word: m[0],
        level: cat.level
      });
    });
  });

  return { ok: hits.length === 0, hits: hits };
};

/* 检查多个字段，合并结果；field 用来告诉用户是哪一栏出的问题 */
window.checkFields = function (fields) {
  var all = [], seen = {};
  Object.keys(fields).forEach(function (name) {
    var r = window.checkContent(fields[name]);
    r.hits.forEach(function (h) {
      var key = name + '|' + h.cat + '|' + h.word;
      if (seen[key]) return;
      seen[key] = true;
      h.field = name;
      all.push(h);
    });
  });
  return { ok: all.length === 0, hits: all };
};
